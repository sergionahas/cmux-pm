#!/usr/bin/env node
// cmux-pm init: sets up a PM workspace for one project.
//   1. copies the runtime (overview, watcher, spawn/close scripts) into the PM directory
//   2. writes pm.config.json and worker-rules.md there (kept if they already exist)
//   3. installs the PM skill into ~/.claude/skills/<skill>/SKILL.md, filled in from the config
//   4. builds the cmux layout, when run from a cmux terminal
// Rerun it any time to upgrade the runtime or re-render the skill after editing pm.config.json.
import { spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { createInterface } from "node:readline/promises";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MARK = "<!-- generated by cmux-pm init; edit pm.config.json and rerun init instead -->";

const HELP = `cmux-pm: a project-manager Claude Code session that runs parallel worker sessions in cmux.

Usage:
  cmux-pm init [options]

Options (anything left out is asked for, or taken from an existing pm.config.json):
  --workdir <path>     where the PM and workers start (your projects folder)   [cwd]
  --dir <path>         where the PM tooling, config and state go          [<workdir>/.cmux-pm]
  --project <name>     project name shown in the overview and the skill
  --repos <a/b,c/d>    GitHub repos whose open PRs the overview lists
  --prefix <ABC>       ticket prefix, e.g. ABC for ABC-123
  --tracker <text>     where tickets live, e.g. "Linear (the linear MCP server)"
  --owner <name>       what the PM calls you                                  [the user]
  --skill <name>       skill name, installed to ~/.claude/skills/<name>        [<project>-pm]
  --skills-dir <path>  install the skill somewhere else            [~/.claude/skills]
  --yes                don't ask; use flags, existing config and defaults
  --force              overwrite an existing SKILL.md not made by cmux-pm
  --no-layout          don't build the cmux layout
  --new                build the layout in a new cmux workspace instead of this one
`;

function parseArgs(argv) {
  const o = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith("--")) { o._.push(a); continue; }
    const k = a.slice(2);
    if (["yes", "force", "no-layout", "new", "help"].includes(k)) o[k] = true;
    else o[k] = argv[++i];
  }
  return o;
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "project";
const expand = (p) => (p?.startsWith("~/") ? join(homedir(), p.slice(2)) : p);
const readJson = (p) => { try { return JSON.parse(readFileSync(p, "utf8")); } catch { return null; } };

function render(tpl, c) {
  const v = {
    project: c.project, dir: c.dir, skill: c.skill, owner: c.owner, workspaceName: c.workspaceName,
    prefix: c.ticketPrefix || "ABC", prefixLower: (c.ticketPrefix || "ABC").toLowerCase(),
    trackerParen: c.tracker ? ` (${c.tracker})` : "",
    trackerLine: c.tracker ? `Tickets live in ${c.tracker}.` : "",
  };
  return tpl.replace(/\{\{(\w+)\}\}/g, (m, k) => (k in v ? v[k] : m)).replace(/\n{3,}/g, "\n\n");
}

async function init(args) {
  const tty = process.stdin.isTTY && !args.yes;
  const rl = tty ? createInterface({ input: process.stdin, output: process.stdout }) : null;
  const ask = async (q, def) => {
    if (!rl) return def;
    const a = (await rl.question(`${q}${def ? ` [${def}]` : ""}: `)).trim();
    return a || def;
  };

  const workdir = resolve(expand(args.workdir ?? (await ask("Working directory (where sessions start)", process.cwd()))));
  const dir = resolve(expand(args.dir ?? (await ask("PM directory (tooling, config, state)", join(workdir, ".cmux-pm")))));
  const prev = readJson(join(dir, "pm.config.json")) ?? {};
  const has = (k) => k in prev && !args[k];
  const pick = async (flag, key, q, def) => args[flag] ?? (key in prev ? prev[key] : await ask(q, def));

  const project = await pick("project", "project", "Project name", prev.project ?? "My project");
  const reposIn = args.repos ?? (has("repos") ? null : await ask("GitHub repos to watch for PRs (owner/repo, comma-separated)", ""));
  const repos = reposIn === null ? prev.repos : reposIn.split(",").map((s) => s.trim()).filter(Boolean);
  const ticketPrefix = (await pick("prefix", "ticketPrefix", "Ticket prefix (e.g. ABC for ABC-123)", "")).toUpperCase();
  const tracker = await pick("tracker", "tracker", "Where tickets live (e.g. Linear, GitHub Issues)", "");
  const owner = await pick("owner", "owner", "What should the PM call you", "the user");
  const skill = slug(await pick("skill", "skill", "Skill name", `${slug(project)}-pm`));
  rl?.close();

  const config = {
    workspaceName: "ADMIN", workerRules: "worker-rules.md",
    claudeArgs: ["--permission-mode", "bypassPermissions"],
    ...prev, project, workdir, repos, ticketPrefix, tracker, owner, skill,
  };

  // Check before writing anything
  const skillsDir = resolve(expand(args["skills-dir"] ?? process.env.CLAUDE_SKILLS_DIR ?? join(homedir(), ".claude", "skills")));
  const skillFile = join(skillsDir, skill, "SKILL.md");
  if (existsSync(skillFile) && !readFileSync(skillFile, "utf8").includes(MARK) && !args.force) {
    console.error(`✗ ${skillFile} exists and wasn't made by cmux-pm. Pick another --skill, or pass --force.`);
    process.exit(1);
  }

  // 1. runtime
  mkdirSync(join(dir, "state"), { recursive: true });
  for (const f of readdirSync(join(ROOT, "src"))) {
    copyFileSync(join(ROOT, "src", f), join(dir, f));
    if (f.endsWith(".sh")) chmodSync(join(dir, f), 0o755);
  }
  copyFileSync(join(ROOT, "README.md"), join(dir, "README.md"));
  writeFileSync(join(dir, ".gitignore"), "state/\n");

  // 2. config and rules
  writeFileSync(join(dir, "pm.config.json"), JSON.stringify(config, null, 2) + "\n");
  const ctx = { ...config, dir };
  const rules = resolve(dir, config.workerRules);
  const newRules = !existsSync(rules);
  if (newRules) writeFileSync(rules, render(readFileSync(join(ROOT, "templates", "worker-rules.md"), "utf8"), ctx));
  writeFileSync(join(dir, "pm-prompt.md"), render(readFileSync(join(ROOT, "templates", "pm-prompt.md"), "utf8"), ctx));

  // 3. skill
  mkdirSync(dirname(skillFile), { recursive: true });
  writeFileSync(skillFile, render(readFileSync(join(ROOT, "templates", "SKILL.md"), "utf8"), ctx).trimEnd() + "\n\n" + MARK + "\n");

  console.log(`✓ PM tooling in ${dir}`);
  console.log(`✓ config: ${join(dir, "pm.config.json")}`);
  console.log(`✓ worker rules: ${rules}${newRules ? " (new: edit the Repo rules section for your project)" : " (kept)"}`);
  console.log(`✓ skill: ${skillFile}`);

  // 4. layout
  if (args["no-layout"]) return;
  if (!process.env.CMUX_WORKSPACE_ID) {
    console.log(`\nNext, from a cmux terminal: ${join(dir, "cmux.sh")}`);
    return;
  }
  const r = spawnSync(join(dir, "cmux.sh"), args.new ? ["--new"] : [], { stdio: "inherit" });
  process.exit(r.status ?? 1);
}

const args = parseArgs(process.argv.slice(2));
const cmd = args._[0];
if (cmd === "init") await init(args);
else { process.stdout.write(HELP); process.exit(args.help || cmd === "help" || !cmd ? 0 : 2); }
